"""Several releasable packages in one repository (``[[release.packages]]``).

A repo that ships more than one thing from one tree -- an app and its plugins, a
library and a tool built on it -- often wants each to keep its own version, tag and
changelog, so that a change to one does not bump the others. Declaring them turns
that on::

    [[release.packages]]
    name = "app"
    path = "app"                                   # files under here belong to it
    version_toml = ["app/pyproject.toml:project.version"]

    [[release.packages]]
    name = "plugin"
    path = "plugins/plugin"
    version_toml = ["plugins/plugin/pyproject.toml:project.version"]

On a merged PR, the packages whose ``path`` the merge commit touched are released,
each by its own semantic-release run: its own version files, tag
(``<name>-v<version>`` unless ``tag_format`` says otherwise), changelog entry and
GitHub Release. Packages the PR did not touch keep their version.

Two things work differently from the single-package flow, both because
semantic-release 8 has no notion of paths:

* **The bump comes from the PR, not from the history.** Under ``release-auto`` the
  level is read from the PR title (``fix:`` patch, ``feat:`` minor, ``!`` or
  ``BREAKING CHANGE`` major; other types release nothing), using the repo's
  ``commit_parser_options``. Letting semantic-release read the commits since the
  package's last tag would also count other packages' commits in that range. An
  explicit ``release-patch``/``-minor``/``-major`` label still forces the level.
* **deputy writes the changelog entry and the GitHub Release.** semantic-release's
  changelog and release notes cover every commit in the range, again including
  other packages', so for packages deputy runs it with ``--no-changelog
  --no-vcs-release`` and records the PR itself: one entry in the package's
  changelog (staged so it lands in the version commit) and a Release for the tag.

Everything here is pure or takes its side effects as parameters, like the rest of
deputy.
"""

from __future__ import annotations

import datetime as _dt
import re
import subprocess
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path

from .config import DEPUTY_RELEASE_KEYS, RELEASE_DEFAULTS, deep_merge

# Keys of a [[release.packages]] entry that are deputy's own, not semantic-release's.
PACKAGE_ONLY_KEYS = ("name", "path", "changelog_file")
DEFAULT_TAG_FORMAT = "{name}-v{version}"
DEFAULT_COMMIT_MESSAGE = "{name} {version}\n\nAutomatically generated by python-semantic-release"

# "type(scope)!: subject"
_TITLE = re.compile(r"^\s*(?P<type>\w+)(?:\([^)]*\))?(?P<bang>!)?\s*:")


@dataclass(frozen=True)
class Package:
    name: str
    path: str
    overrides: dict  # semantic-release overrides for this package's runs
    changelog_file: str
    version_json: tuple[str, ...] = field(default_factory=tuple)

    @property
    def tag_format(self) -> str:
        return self.overrides["tag_format"]

    def tag(self, version: str) -> str:
        return self.tag_format.replace("{version}", version)


def release_packages(cfg: dict) -> list[Package]:
    """The ``[[release.packages]]`` declared in deputy.toml (empty: single-package repo).

    Each package's semantic-release config is the repo's shared ``[release]`` keys
    with the package's own keys on top. Version locations (``version_toml``,
    ``version_variables``) are *not* inherited -- a root ``pyproject.toml`` is not
    every package's version file -- so each package states its own.

    Raises ``ValueError`` for an entry without ``name``/``path`` or a repeated name.
    """
    release = dict(cfg.get("release", {}))
    entries = release.pop("packages", []) or []
    shared = {k: v for k, v in release.items() if k not in DEPUTY_RELEASE_KEYS}
    shared.pop("version_toml", None)
    shared.pop("version_variables", None)

    packages: list[Package] = []
    seen: set[str] = set()
    for entry in entries:
        name, path = entry.get("name"), entry.get("path")
        if not name or not path:
            raise ValueError(f"[[release.packages]] entry needs a name and a path: {entry!r}")
        if name in seen:
            raise ValueError(f"[[release.packages]] name {name!r} is declared twice")
        seen.add(name)
        own = {
            k: v
            for k, v in entry.items()
            if k not in PACKAGE_ONLY_KEYS and k not in DEPUTY_RELEASE_KEYS
        }
        overrides = deep_merge(shared, own)
        overrides.setdefault("version_toml", [])
        overrides.setdefault("tag_format", DEFAULT_TAG_FORMAT.replace("{name}", name))
        overrides.setdefault("commit_message", DEFAULT_COMMIT_MESSAGE.replace("{name}", name))
        path = str(path).replace("\\", "/").strip("/")
        packages.append(
            Package(
                name=name,
                path=path,
                overrides=overrides,
                changelog_file=entry.get("changelog_file", f"{path}/CHANGELOG.md"),
                version_json=tuple(entry.get("version_json", [])),
            )
        )
    return packages


def touched_packages(packages: Sequence[Package], files: Sequence[str]) -> list[Package]:
    """The packages that own at least one of ``files`` (repo-relative paths)."""
    norm = [f.replace("\\", "/").lstrip("/") for f in files]
    return [p for p in packages if any(f == p.path or f.startswith(p.path + "/") for f in norm)]


def flag_from_title(title: str, parser_options: dict | None = None) -> str | None:
    """The bump a conventional PR title asks for, as a semantic-release force flag.

    ``!`` before the colon or ``BREAKING CHANGE`` in the title is a major bump;
    otherwise the type is looked up in ``minor_tags``/``patch_tags`` (deputy's
    defaults when not configured). Any other type -- or a title that is not
    conventional -- releases nothing (None).
    """
    m = _TITLE.match(title or "")
    if not m:
        return None
    if m.group("bang") or "BREAKING CHANGE" in title:
        return "--major"
    defaults = RELEASE_DEFAULTS["commit_parser_options"]
    opts = {**defaults, **(parser_options or {})}
    kind = m.group("type").lower()
    if kind in [t.lower() for t in opts.get("minor_tags", [])]:
        return "--minor"
    if kind in [t.lower() for t in opts.get("patch_tags", [])]:
        return "--patch"
    return None


def package_flag(decision_flag: str | None, title: str, package: Package) -> str | None:
    """The force flag for one package: the label's, or the title's under release-auto."""
    if decision_flag is None:
        return None
    if decision_flag:
        return decision_flag
    return flag_from_title(title, package.overrides.get("commit_parser_options"))


def changed_files(merge_sha: str | None, runner: Callable = subprocess.run) -> list[str]:
    """Files the merge commit changed against its first parent (``HEAD`` if no sha).

    Works for squash, rebase and merge commits: the first parent is ``main`` before
    the merge either way. Raises ``RuntimeError`` when git cannot say -- guessing
    "nothing changed" would release nothing, silently.
    """
    rev = merge_sha or "HEAD"
    res = runner(
        ["git", "diff", "--name-only", f"{rev}^1", rev],
        capture_output=True,
        text=True,
        check=False,
    )
    if getattr(res, "returncode", 1) != 0:
        raise RuntimeError(
            f"git could not list the files changed by {rev}: {getattr(res, 'stderr', '')}"
        )
    return [line.strip() for line in (res.stdout or "").splitlines() if line.strip()]


def changelog_entry(tag: str, title: str, number: int, url: str | None, today: _dt.date) -> str:
    ref = f"[#{number}]({url})" if url else f"#{number}"
    return f"## {tag} ({today.isoformat()})\n\n* {title} ({ref})\n"


def add_changelog_entry(path: Path, entry: str) -> None:
    """Insert ``entry`` above the previous entries (below a leading ``# `` heading)."""
    text = path.read_text(encoding="utf-8") if path.is_file() else "# CHANGELOG\n"
    lines = text.splitlines(keepends=True)
    at = 0
    if lines and lines[0].startswith("# "):
        at = 1
        while at < len(lines) and not lines[at].strip():
            at += 1
    head = "".join(lines[:at])
    if head and not head.endswith("\n\n"):
        head = head.rstrip("\n") + "\n\n"
    rest = "".join(lines[at:])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(head + entry + ("\n" + rest if rest else ""), encoding="utf-8")
